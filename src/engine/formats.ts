/**
 * Detect format from a file (by extension, MIME type, or fallback)
 */
export function detectFormat(file: File): FormatDefinition {
  const name = file.name.toLowerCase();
  const mime = file.type.toLowerCase();

  if (name.endsWith('.pi')) return FORMATS.pi;
  if (name.endsWith('.vector3') || name.endsWith('.vec3')) return FORMATS.vector3;
  if (name.endsWith('.quaternion') || name.endsWith('.quat')) return FORMATS.quaternion;
  if (name.endsWith('.nes')) return FORMATS.nes;
  if (name.endsWith('.z64')) return FORMATS.z64;
  if (name.endsWith('.n64')) return FORMATS.n64;
  if (name.endsWith('.v64')) return FORMATS.v64;
  if (name.endsWith('.wad')) return FORMATS.wad;
  if (name.endsWith('.sfc')) return FORMATS.sfc;
  if (name.endsWith('.smc')) return FORMATS.smc;
  if (name.endsWith('.gba')) return FORMATS.gba;
  if (name.endsWith('.gbc')) return FORMATS.gbc;
  if (name.endsWith('.gb')) return FORMATS.gb;
  if (name.endsWith('.nds')) return FORMATS.nds;
  if (name.endsWith('.cia')) return FORMATS.cia;
  if (name.endsWith('.wbfs')) return FORMATS.wbfs;
  if (name.endsWith('.pbp')) return FORMATS.pbp;
  if (name.endsWith('.nsp')) return FORMATS.nsp;
  if (name.endsWith('.xci')) return FORMATS.xci;
  if (name.endsWith('.iso')) return FORMATS.iso_disc || FORMATS.iso;
  if (name.endsWith('.bruh')) return FORMATS.bruh;
  if (name.endsWith('.chr')) return FORMATS.chr;
  if (name.endsWith('.xapk')) return FORMATS.xapk;
  if (name.endsWith('.apk')) return FORMATS.apk;
  if (name.endsWith('.truehd')) return FORMATS.truehd;
  if (name.endsWith('.thd')) return FORMATS.thd;
  if (name.endsWith('.typ')) return FORMATS.typ || FORMATS.txt;
  if (name.endsWith('.adoc')) return FORMATS.adoc || FORMATS.txt;
  if (name.endsWith('.bib')) return FORMATS.bib || FORMATS.txt;
  if (name.endsWith('.dj')) return FORMATS.dj || FORMATS.txt;
  if (name.endsWith('.ipynb')) return FORMATS.ipynb || FORMATS.json;

  // Try matching by extension
  for (const fmt of Object.values(FORMATS)) {
    if (name.endsWith(fmt.extension.toLowerCase())) {
      return fmt;
    }
  }

  // Handle common aliases
  if (name.endsWith('.jpeg')) return FORMATS.jpeg || FORMATS.png;
  if (name.endsWith('.yml')) return FORMATS.yaml || FORMATS.json;
  if (name.endsWith('.htm')) return FORMATS.html || FORMATS.txt;

  // Try matching by MIME type
  if (mime) {
    for (const fmt of Object.values(FORMATS)) {
      if (fmt.mimeTypes.includes(mime)) {
        return fmt;
      }
    }
  }

  // Fallback by general category
  if (mime.startsWith('image/')) return FORMATS.png;
  if (mime.startsWith('audio/')) return FORMATS.wav;
  if (mime.startsWith('video/')) return FORMATS.mp4 || FORMATS.webm;
  if (mime.startsWith('text/')) return FORMATS.txt;

  return FORMATS.txt;
}
